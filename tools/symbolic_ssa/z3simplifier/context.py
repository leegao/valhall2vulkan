#!/usr/bin/env python3
"""
Core data structures for the Z3 term and predicate simplification framework.

Defines:
  - `SimplifyQuery`: immutable representation of an equivalence/miter query
    `(preconditions & guard) => (lhs == rhs)` along with side-obligations
    generated by conditioned unification and soundness/abstraction metadata.
  - `SideObligation`: a weakest-liberal-precondition / congruence obligation
    `preconditions => (lhs == rhs)` that justifies a conditioned unification
    substitution when discharged as UNSAT.
  - `PassStats` and `RewriteStats`: structured telemetry for observability,
    regression testing, and debugging.
  - `SimplificationContext`: shared mutable state passed across passes in a
    pipeline run (fresh symbol allocator, budget knobs, debug trace hooks).
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from typing import Any, Callable, Dict, List, Optional, Tuple

import z3

from tools.symbolic_ssa.z3utils import dsl


@dataclass(frozen=True)
class SideObligation:
    """
    A congruence/WLP side-obligation emitted by conditioned unification.

    If `(preconditions & guard) => (lhs == rhs)` is proved UNSAT (i.e. valid),
    then replacing `lhs` and `rhs` with `fresh_var` in the parent query is
    100% equivalence-preserving.
    """

    obligation_id: str
    fresh_var: dsl.ExprRef
    lhs: dsl.ExprRef
    rhs: dsl.ExprRef
    guard: Optional[dsl.BoolRef] = None
    reason: str = ""
    discharged: Optional[bool] = None
    elapsed_ms: float = 0.0


@dataclass(frozen=True)
class SimplifyQuery:
    """
    Immutable miter / predicate query flowing through a `Z3SimplifierPipeline`.

    Represents the refutation query:
      `And(*preconditions) & guard & (lhs != rhs)` (when `predicate` is None)
    or an explicit boolean refutation predicate `predicate` (when already lowered
    or discharged to `BoolVal(False)`).

    `is_overapprox` is True whenever an UNSAT-sound-only abstraction pass
    (such as `TheoryPurifyRealPass`, `InjectiveBridgeUnwrapPass`, or
    `ExactCseUnificationPass`) has transformed the query. Callers must never
    treat a `SAT` result on an over-approximated query as a true counterexample
    without refining or falling back to the exact/equivalence-preserving query.

    `side_obligations` holds discharged WLP obligations (`discharged=True`)
    that justified `cu_k` unifications. `residual_obligations` holds undischarged
    structural anti-unification congruence conditions (`discharged=False`) whose
    conjunction implies `lhs == rhs`.
    """

    lhs: dsl.ExprRef
    rhs: dsl.ExprRef
    guard: Optional[dsl.BoolRef] = None
    preconditions: Tuple[dsl.BoolRef, ...] = ()
    predicate: Optional[dsl.ExprRef] = None
    side_obligations: Tuple[SideObligation, ...] = ()
    residual_obligations: Tuple[SideObligation, ...] = ()
    is_overapprox: bool = False
    pure_theory: Optional[str] = None
    abstraction_map: Tuple[Tuple[dsl.ExprRef, dsl.ExprRef], ...] = ()
    notes: Tuple[str, ...] = ()

    def with_terms(
        self,
        lhs: dsl.ExprRef,
        rhs: dsl.ExprRef,
        guard: Optional[dsl.BoolRef] = None,
        preconditions: Optional[Tuple[dsl.BoolRef, ...]] = None,
        **kwargs: Any,
    ) -> "SimplifyQuery":
        """Return a shallow updated copy preserving metadata."""
        return replace(
            self,
            lhs=lhs,
            rhs=rhs,
            guard=guard if guard is not None else self.guard,
            preconditions=preconditions if preconditions is not None else self.preconditions,
            **kwargs,
        )

    def realize_z3(self) -> "SimplifyQuery":
        """Realize all DSL `Z3Expr` terms in this query into concrete `z3.ExprRef`s (memoized)."""
        lhs = dsl.lower(self.lhs)
        rhs = dsl.lower(self.rhs)
        guard = dsl.lower(self.guard) if self.guard is not None else None
        pres = tuple(dsl.lower(p) for p in self.preconditions)
        pred = dsl.lower(self.predicate) if self.predicate is not None else None
        if (
            lhs is self.lhs
            and rhs is self.rhs
            and guard is self.guard
            and pred is self.predicate
            and all(a is b for a, b in zip(pres, self.preconditions))
        ):
            return self
        return replace(self, lhs=lhs, rhs=rhs, guard=guard, preconditions=pres, predicate=pred)

    def is_trivially_unsat(self) -> bool:
        """Return True if the query is already syntactically proved UNSAT (works lazily on DSL)."""
        if self.predicate is not None and dsl.is_false(self.predicate):
            return True
        if self.guard is not None and dsl.is_false(self.guard):
            return True
        if dsl.expr_eq(self.lhs, self.rhs):
            return True
        return False

    def to_refutation_predicate(self) -> z3.ExprRef:
        """Materialize the boolean refutation formula `guard & (lhs != rhs)` as a concrete `z3.BoolRef`."""
        if self.predicate is not None:
            return dsl.lower(self.predicate)
        if dsl.expr_eq(self.lhs, self.rhs):
            return z3.BoolVal(False)
        lhs_z = dsl.lower(self.lhs)
        rhs_z = dsl.lower(self.rhs)
        diff = lhs_z != rhs_z
        if self.guard is None or dsl.is_true(self.guard):
            return diff
        if dsl.is_false(self.guard):
            return z3.BoolVal(False)
        return z3.And(dsl.lower(self.guard), diff)


@dataclass
class PassStats:
    """Execution metrics for a single pass invocation."""

    pass_name: str
    changed: bool
    rewrites: int = 0
    elapsed_ms: float = 0.0
    detail: str = ""


@dataclass
class RewriteStats:
    """Aggregated telemetry for a complete simplification pipeline run."""

    pass_stats: List[PassStats] = field(default_factory=list)
    total_ms: float = 0.0
    rounds: int = 0
    initial_ast_nodes: int = 0
    final_ast_nodes: int = 0

    @property
    def total_rewrites(self) -> int:
        return sum(p.rewrites for p in self.pass_stats)

    def summary_line(self) -> str:
        fired = [f"{p.pass_name}({p.rewrites})" for p in self.pass_stats if p.changed]
        fired_s = ",".join(fired) if fired else "none"
        return (
            f"nodes={self.initial_ast_nodes}->{self.final_ast_nodes} "
            f"rewrites={self.total_rewrites} elapsed={self.total_ms:.2f}ms fired=[{fired_s}]"
        )


@dataclass
class SimplificationContext:
    """
    Shared context passed to every pass in a pipeline execution.

    Provides deterministic fresh symbol generation, configurable node/time
    guards (preventing exponential blowup in polynomial expansion or DAG walks),
    and optional trace logging.
    """

    max_som_nodes: int = 256
    max_dag_nodes: int = 50000
    max_unify_candidates: int = 64
    wlp_timeout_ms: int = 50
    enable_overapprox: bool = True
    verbose: bool = False
    trace_fn: Optional[Callable[[str], None]] = None
    _fresh_counter: int = 0
    _symbol_cache: Dict[Tuple[str, Any], dsl.ExprRef] = field(default_factory=dict)

    def fresh_const(self, prefix: str, sort: dsl.SortRef) -> dsl.ExprRef:
        """Allocate a deterministic fresh DSL constant of the requested sort."""
        idx = self._fresh_counter
        self._fresh_counter += 1
        return dsl.Const(f"{prefix}_{idx}", sort)

    def intern_const(self, cache_key: Tuple[str, Any], name: str, sort: dsl.SortRef) -> dsl.ExprRef:
        """Return a cached DSL constant for `cache_key`, creating it on first use."""
        existing = self._symbol_cache.get(cache_key)
        if existing is not None:
            return existing
        sym = dsl.Const(name, sort)
        self._symbol_cache[cache_key] = sym
        return sym

    def trace(self, msg: str) -> None:
        """Emit a debug trace message if tracing is enabled."""
        if self.trace_fn is not None:
            self.trace_fn(msg)


@dataclass
class SimplifyResult:
    """Output of `PassPipeline.run(query, ctx)`."""

    query: SimplifyQuery
    exact_query: SimplifyQuery
    stats: RewriteStats
