@dataclass(frozen=True, slots=True)
class Z3OpBridge:
    op: BridgeOp
    arg: Any
    raw: Optional[z3.ExprRef] = None

    def lower(self) -> z3.ExprRef:
        a = lower(self.arg)
        if self.raw is not None:
            return self.raw.decl()(a)
        if self.op in (BridgeOp.F32_TO_BV32, BridgeOp.REAL2BV32, BridgeOp.F32_TO_S32, BridgeOp.F32_TO_U32):
            return z3.Function(self.op.value, z3.RealSort(), z3.BitVecSort(32))(a)
        if self.op in (BridgeOp.BV32_TO_F32, BridgeOp.BV32_TO_REAL, BridgeOp.S32_TO_F32, BridgeOp.U32_TO_F32):
            return z3.Function(self.op.value, z3.BitVecSort(32), z3.RealSort())(a)
        if self.op is BridgeOp.F16_TO_BV16:
            return z3.Function(self.op.value, z3.RealSort(), z3.BitVecSort(16))(a)
        if self.op is BridgeOp.BV16_TO_F16:
            return z3.Function(self.op.value, z3.BitVecSort(16), z3.RealSort())(a)
        if self.op is BridgeOp.F64_TO_BV64:
            return z3.Function(self.op.value, z3.RealSort(), z3.BitVecSort(64))(a)
        return z3.Function(self.op.value, z3.BitVecSort(64), z3.RealSort())(a)


