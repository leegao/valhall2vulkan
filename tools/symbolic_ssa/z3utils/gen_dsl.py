def _collect_z3_enum_entries(prefix: str, suffix: str = "") -> List[Tuple[str, int]]:
    """Inspect `dir(z3)` and collect `(name, int_value)` pairs matching prefix/suffix."""
    entries: List[Tuple[str, int]] = []
    seen_vals: set[int] = set()
    for name in sorted(dir(z3)):
        if not name.startswith(prefix):
            continue
        if suffix and not name.endswith(suffix):
            continue
        val = getattr(z3, name, None)
        if isinstance(val, int) and not isinstance(val, bool):
            short = name[len(prefix):]
            if suffix:
                short = short[:-len(suffix)]
            if short and short[0].isdigit():
                short = "_" + short
            if val not in seen_vals:
                seen_vals.add(val)
                entries.append((short, val))
    return entries


def _introspect_z3_dunders() -> List[Tuple[str, List[str]]]:
    """Introspect operator dunders on live Z3 Ref classes for self-documenting provenance."""
    out: List[Tuple[str, List[str]]] = []
    obj_dunders = set(dir(object))
    for cls in (z3.ExprRef, z3.BoolRef, z3.BitVecRef, z3.ArithRef, z3.FPRef, z3.ArrayRef):
        dunders = sorted(
            m for m in dir(cls)
            if m.startswith("__") and m.endswith("__")
            and m not in obj_dunders
            and m not in ("__dict__", "__module__", "__weakref__", "__del__", "__copy__", "__deepcopy__", "__nonzero__")
        )
        out.append((cls.__name__, dunders))
    return out


