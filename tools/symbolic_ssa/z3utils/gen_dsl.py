class Z3PolyExpr(Z3Expr):
    """
    Sort-polymorphic DSL expression base (`If`, `Select`, `Bridge`, `UFApp`, `Z3Other`).

    Dispatches Python operators according to `self.sort_kind()` so polymorphic
    nodes behave identically to their concrete Z3 sort counterparts.
    """

    __slots__ = ()

    def is_real(self) -> bool:
        return self.sort_kind() == Z3SortKind.REAL

    def is_int(self) -> bool:
        return self.sort_kind() == Z3SortKind.INT

    def size(self) -> int:
        return self.to_z3.size()

    def ebits(self) -> int:
        return self.to_z3.ebits()

    def sbits(self) -> int:
        return self.to_z3.sbits()

    def range_sort_kind(self) -> Z3SortKind:
        return Z3SortKind(self.to_z3.range().kind())

    def range_bv_size(self) -> Optional[int]:
        rng = self.to_z3.range()
        return rng.size() if isinstance(rng, z3.BitVecSortRef) else None

    def __getitem__(self, idx: Any) -> "Z3Expr":
        return Select(self, idx)

    def __add__(self, other: Any) -> "Z3Expr":
        sk = self.sort_kind()
        if sk == Z3SortKind.BV:
            w = self.size()
            return Z3OpBvAdd(self, _coerce_bv(other, w), w)
        if sk == Z3SortKind.REAL:
            return Z3OpRealAdd((self, _coerce_real(other)))
        if sk == Z3SortKind.INT:
            if isinstance(other, (float, fractions.Fraction)) or is_real(other):
                return Z3OpRealAdd((Z3OpToReal(self), _coerce_real(other)))
            return Z3OpIntAdd((self, _coerce_int(other)))
        if sk == Z3SortKind.FLOATING_POINT:
            return Z3OpFPBinary(FpBinaryOp.ADD, self, _wrap_raw_if_needed(other))
        raise TypeError(f"Unsupported + on sort {{sk}}")

    def __radd__(self, other: Any) -> "Z3Expr":
        sk = self.sort_kind()
        if sk == Z3SortKind.BV:
            w = self.size()
            return Z3OpBvAdd(_coerce_bv(other, w), self, w)
        if sk == Z3SortKind.REAL:
            return Z3OpRealAdd((_coerce_real(other), self))
        if sk == Z3SortKind.INT:
            if isinstance(other, (float, fractions.Fraction)) or is_real(other):
                return Z3OpRealAdd((_coerce_real(other), Z3OpToReal(self)))
            return Z3OpIntAdd((_coerce_int(other), self))
        raise TypeError(f"Unsupported + on sort {{sk}}")

