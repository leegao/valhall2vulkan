def lower(node: Any) -> z3.ExprRef:
    """Lower a DSL `Z3Expr` (or pass through a raw `z3.ExprRef`) to `z3.ExprRef`."""
    if isinstance(node, z3.ExprRef):
        return node
    if isinstance(node, Z3Expr):
        return node.to_z3
    return node.lower()


def to_z3(node: Any) -> z3.ExprRef:
    """Alias for `lower(node)` realizing a concrete `z3.ExprRef`."""
    return lower(node)


def unwrap(node: Any) -> z3.ExprRef:
    """Return cached `.raw` `z3.ExprRef` if available, else realize via `.to_z3`."""
    if isinstance(node, z3.ExprRef):
        return node
    if isinstance(node, Z3Expr):
        return node.to_z3
    raw = getattr(node, "raw", None)
    if raw is not None:
        return raw
    return node.lower()


