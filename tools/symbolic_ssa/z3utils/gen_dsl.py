def _coerce_bv(other: Any, width: int) -> Z3Expr:
    if isinstance(other, Z3Expr):
        return other
    if isinstance(other, int) and not isinstance(other, bool):
        return Z3BvConst(other & ((1 << width) - 1), width)
    if isinstance(other, z3.ExprRef):
        return lift(other, depth=1)
    raise TypeError(f"Cannot coerce {{type(other).__name__}} to BitVec({{width}})")


def _coerce_bool(other: Any) -> Z3Expr:
    if isinstance(other, Z3Expr):
        return other
    if isinstance(other, bool):
        return Z3BoolConst(other)
    if isinstance(other, z3.ExprRef):
        return lift(other, depth=1)
    raise TypeError(f"Cannot coerce {{type(other).__name__}} to Bool")


def _coerce_real(other: Any) -> Z3Expr:
    if isinstance(other, Z3Expr):
        if is_int(other):
            return Z3OpToReal(other)
        return other
    if isinstance(other, bool):
        raise TypeError("Cannot coerce bool to Real")
    if isinstance(other, int):
        return Z3RealConst(other, 1)
    if isinstance(other, float):
        frac = fractions.Fraction(other)
        return Z3RealConst(frac.numerator, frac.denominator)
    if isinstance(other, fractions.Fraction):
        return Z3RealConst(other.numerator, other.denominator)
    if isinstance(other, str):
        frac = fractions.Fraction(other)
        return Z3RealConst(frac.numerator, frac.denominator)
    if isinstance(other, z3.ExprRef):
        w = lift(other, depth=1)
        return Z3OpToReal(w) if is_int(w) else w
    raise TypeError(f"Cannot coerce {{type(other).__name__}} to Real")


def _coerce_int(other: Any) -> Z3Expr:
    if isinstance(other, Z3Expr):
        return other
    if isinstance(other, int) and not isinstance(other, bool):
        return Z3IntConst(other)
    if isinstance(other, z3.ExprRef):
        return lift(other, depth=1)
    raise TypeError(f"Cannot coerce {{type(other).__name__}} to Int")


def _coerce_like(ref: Z3Expr, other: Any) -> Z3Expr:
    if isinstance(other, Z3Expr):
        return other
    if isinstance(other, z3.ExprRef):
        return lift(other, depth=1)
    sk = ref.sort_kind()
    if sk == Z3SortKind.BV:
        return _coerce_bv(other, _bv_size(ref))
    if sk == Z3SortKind.BOOL:
        return _coerce_bool(other)
    if sk == Z3SortKind.REAL:
        return _coerce_real(other)
    if sk == Z3SortKind.INT:
        return _coerce_int(other)
    if sk == Z3SortKind.FLOATING_POINT:
        return Z3FPConst(other, _fp_ebits(ref), _fp_sbits(ref))
    raise TypeError(f"Cannot coerce {{type(other).__name__}} to sort {{sk}}")


def _struct_eq_val(a: Any, b: Any) -> bool:
    if a is b:
        return True
    if isinstance(a, Z3Expr):
        return a.eq(b)
    if isinstance(b, Z3Expr):
        return b.eq(a)
    if isinstance(a, z3.AstRef) and isinstance(b, z3.AstRef):
        return a.eq(b)
    if isinstance(a, tuple) and isinstance(b, tuple):
        return len(a) == len(b) and all(_struct_eq_val(x, y) for x, y in zip(a, b))
    return a == b


def _struct_hash_val(v: Any) -> int:
    if isinstance(v, Z3Expr):
        return hash(v)
    if isinstance(v, z3.AstRef):
        return v.get_id()
    if isinstance(v, tuple):
        return hash(tuple(_struct_hash_val(x) for x in v))
    return hash(v)


class Z3Expr:
    """
    Base class for all immutable lazy-lowering Z3 DSL expression nodes.

    Provides Z3-API-compatible structural equality (`.eq()`), symbolic equality
    (`==`, `!=` returning `Z3OpEq` / `Z3OpDistinct`), stable `.get_id()`,
    and lazy memoized `.to_z3` / `.lower()`.
    """

    __slots__ = ()

    @property
    def to_z3(self) -> z3.ExprRef:
        """Lazily lower this DSL node to a concrete `z3.ExprRef` and memoize the result."""
        cached = self._z3_cache  # type: ignore[attr-defined]
        if cached is not None:
            return cached
        built = self._build_z3()
        object.__setattr__(self, "_z3_cache", built)
        return built

    def lower(self) -> z3.ExprRef:
        """Return the memoized lowered `z3.ExprRef` for this DSL node."""
        return self.to_z3

    def _build_z3(self) -> z3.ExprRef:
        raise NotImplementedError

    def sort_kind(self) -> Z3SortKind:
        return Z3SortKind(self.to_z3.sort_kind())

    def sort(self) -> z3.SortRef:
        return self.to_z3.sort()

    def children(self) -> Tuple[Any, ...]:
        return ()

    def num_args(self) -> int:
        return len(self.children())

    def arg(self, i: int) -> Any:
        return self.children()[i]

    def decl(self) -> z3.FuncDeclRef:
        return self.to_z3.decl()

    def op_kind(self) -> Z3OpKind:
        return Z3OpKind(self.to_z3.decl().kind())

    def sexpr(self) -> str:
        return self.to_z3.sexpr()

    def get_id(self) -> int:
        cached = self._z3_cache  # type: ignore[attr-defined]
        if cached is not None:
            return cached.get_id()
        return id(self)

    def as_ast(self) -> Any:
        return self.to_z3.as_ast()

    def eq(self, other: Any) -> bool:
        """DAG-safe structural equality returning Python `bool` without forcing Z3 lowering."""
        if self is other:
            return True
        if isinstance(other, z3.ExprRef):
            return self.to_z3.eq(other)
        if type(self) is not type(other):
            return False
        if hash(self) != hash(other):
            return False
        seen: set[Tuple[int, int]] = set()
        stack: List[Tuple[Any, Any]] = [(self, other)]
        while stack:
            a, b = stack.pop()
            if a is b:
                continue
            if isinstance(a, Z3Expr):
                if isinstance(b, z3.ExprRef):
                    if not a.to_z3.eq(b):
                        return False
                    continue
                if type(a) is not type(b):
                    return False
                if hash(a) != hash(b):
                    return False
                pair = (id(a), id(b))
                if pair in seen:
                    continue
                seen.add(pair)
                for fname in a._struct_fields:  # type: ignore[attr-defined]
                    stack.append((getattr(a, fname), getattr(b, fname)))
            elif isinstance(b, Z3Expr):
                if isinstance(a, z3.ExprRef):
                    if not b.to_z3.eq(a):
                        return False
                    continue
                return False
            elif isinstance(a, z3.AstRef) and isinstance(b, z3.AstRef):
                if not a.eq(b):
                    return False
            elif isinstance(a, tuple) and isinstance(b, tuple):
                if len(a) != len(b):
                    return False
                for x, y in zip(a, b):
                    stack.append((x, y))
            else:
                if a != b:
                    return False
        return True

    def __hash__(self) -> int:
        cached = self._hash_cache  # type: ignore[attr-defined]
        if cached is not None:
            return cached
        acc = hash(type(self))
        for fname in self._struct_fields:  # type: ignore[attr-defined]
            acc = hash((acc, _struct_hash_val(getattr(self, fname))))
        object.__setattr__(self, "_hash_cache", acc)
        return acc

    def __bool__(self) -> bool:
        raise TypeError(
            "Symbolic Z3Expr cannot be cast to concrete bool; use .eq() or explicit comparison"
        )

    def __eq__(self, other: Any) -> Any:
        if other is None:
            return False
        rhs = _coerce_like(self, other)
        return Z3OpEq(self, rhs)

    def __ne__(self, other: Any) -> Any:
        if other is None:
            return True
        rhs = _coerce_like(self, other)
        return Z3OpDistinct(self, rhs)


