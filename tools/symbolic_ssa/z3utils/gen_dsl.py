def _emit_node_class(spec: NodeSpec) -> str:
    """Render a single frozen slotted dataclass from its `NodeSpec`."""
    lines: List[str] = [
        "@dataclass(frozen=True, slots=True, eq=False)",
        f"class {spec.cls_name}({spec.base_cls}):",
    ]
    for f in spec.fields:
        if f.default is not None:
            lines.append(f"    {f.name}: {f.type_ann} = {f.default}")
        else:
            lines.append(f"    {f.name}: {f.type_ann}")
    struct_fnames = tuple(f.name for f in spec.fields)
    lines.append(
        "    _z3_cache: Optional[z3.ExprRef] = field(default=None, init=False, repr=False, compare=False)"
    )
    lines.append(
        "    _hash_cache: Optional[int] = field(default=None, init=False, repr=False, compare=False)"
    )
    lines.append(
        f"    _struct_fields: ClassVar[Tuple[str, ...]] = {struct_fnames!r}"
    )
    lines.append("")
    lines.append("    def _build_z3(self) -> z3.ExprRef:")
    lines.append(f"        {spec.lower_body}")
    if spec.children_expr != "()":
        lines.append("")
        lines.append("    def children(self) -> Tuple[Any, ...]:")
        lines.append(f"        return {spec.children_expr}")
    if spec.op_kind_expr is not None:
        lines.append("")
        lines.append("    def op_kind(self) -> Z3OpKind:")
        lines.append(f"        return {spec.op_kind_expr}")
    if spec.extra_methods:
        lines.append(spec.extra_methods.rstrip())
    return "\n".join(lines)


